/**
 * Runs the four incident scenarios against the REAL Airwallex sandbox (test money only)
 * and writes docs/SANDBOX_RUN_LOG.md. Credentials come from ../.env and are never printed.
 *   npm run sandbox:run -w server
 */
import dotenv from "dotenv";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
dotenv.config({ path: [".env", "../.env"], quiet: true } as any);
if (!process.env.AIRWALLEX_CLIENT_ID || !process.env.AIRWALLEX_API_KEY) {
  console.error("Set AIRWALLEX_CLIENT_ID and AIRWALLEX_API_KEY in .env first.");
  process.exit(1);
}
process.env.AUDIT_LOG_PATH ||= join(mkdtempSync(join(tmpdir(), "atlas-sbx-")), "audit.jsonl");
process.env.CONNECTOR = "airwallex";
delete process.env.ANTHROPIC_API_KEY; // deterministic planner for a reproducible log
const { Commander } = await import("../src/service.js");
const { AirwallexConnector, sandboxBeneficiaries } = await import("../src/connectors/airwallex.js");
type Rec = import("../src/connectors/airwallex.js").ApiCallRecord;

const c = new Commander();
const aw = c.connector as InstanceType<typeof AirwallexConnector>;
let calls: Rec[] = [];
aw.onCall = (r) => calls.push(r);
const take = () => {
  const out = calls;
  calls = [];
  return out;
};
const md: string[] = [];
const now = () =>
  new Date().toLocaleString("en-US", { timeZone: "America/Phoenix", dateStyle: "medium", timeStyle: "short" }) + " AZ (MST)";
const table = (rows: Rec[]) =>
  [
    "| Call | HTTP | Airwallex code / object status | id |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| \`${r.method} ${r.path}\` | ${r.status} | ${[r.code, r.objectStatus].filter(Boolean).join(" / ") || "-"} | ${r.id ? "`" + r.id + "`" : "-"} |`),
  ].join("\n");
const section = (title: string, lines: string[]) => {
  md.push(`\n## ${title}\n`, ...lines, "", "Airwallex calls:", "", table(take()), "");
  console.log("done:", title);
};
const summary: string[] = [];

md.push(
  "# Airwallex sandbox run log",
  "",
  `Run: ${now()} against \`https://api.sandbox.airwallex.com\` (account: Sandbox Business, test money only).`,
  "Generated by `npm run sandbox:run -w server` (server/scripts/sandbox-run.ts). Planner: rule-based. No credentials, tokens or bank account numbers are recorded here; transfer and beneficiary ids are sandbox test objects.",
);

// 0. Auth, balance, beneficiaries
const bal = await aw.balances();
const usd = bal.find((b) => b.currency === "USD");
const acme = await aw.resolveBeneficiary("vendor-acme");
const bad = await aw.resolveBeneficiary("vendor-bad");
const badDetails = structuredClone(sandboxBeneficiaries["vendor-bad"]);
(badDetails.beneficiary as any).bank_details.account_routing_value1 = "12345";
const v = await aw.validateBeneficiary({ beneficiary: badDetails.beneficiary, transfer_methods: badDetails.transfer_methods });
section("0. Setup: token, balance, beneficiaries", [
  `- Token: login returned 201; cached and refreshed 5 minutes before its 30-minute expiry.`,
  `- USD balance before the run: available ${usd?.available_amount} (sandbox test funds, no funding needed).`,
  `- Logical beneficiary \`vendor-acme\` -> Airwallex beneficiary \`${acme}\` (nickname atlas-vendor-acme).`,
  `- Logical beneficiary \`vendor-bad\` -> Airwallex beneficiary \`${bad}\` (nickname atlas-vendor-bad).`,
  `- Validate a "corrected" vendor-bad record with a 5-digit routing number: valid=${v.valid}; errors: ${v.errors.map((e) => e.source + " (code " + e.code + ")").join(", ")}.`,
]);

// 1. Duplicate payout
{
  const i = await c.simulate("duplicate");
  const r = await c.run(i.id);
  const replay = await aw.createPayout({
    beneficiaryId: "vendor-acme",
    amount: i.payout!.amount,
    currency: "USD",
    reference: i.payout!.reference,
    idempotencyKey: i.payout!.idempotencyKey,
  });
  const sameKey = await aw.findByRequestId(i.payout!.idempotencyKey);
  const ok = r.status === "blocked" && replay.providerDuplicate === true && replay.id === i.payout!.id;
  summary.push(`| 1. Duplicate payout | ${ok ? "PASS" : "CHECK"} | Original $${i.payout!.amount} transfer reached PAID; agent retry blocked (${r.actions![0].policy.ruleHits.join(", ")}); replayed request_id -> HTTP 400 duplicate_request_id, same transfer returned |`);
  section("1. Duplicate payout / retry storm", [
    `- Created original transfer \`${i.payout!.id}\` ($${i.payout!.amount} USD, ref ${i.payout!.reference}, request_id \`${i.payout!.idempotencyKey}\`), simulated SENT -> PAID. Provider status now: **${i.payout!.providerStatus}**.`,
    `- Agent plan: ${r.actions!.map((a) => a.action.type + " => " + a.policy.decision + " (" + a.policy.ruleHits.join(", ") + "): " + a.outcome).join("; ")}.`,
    `- Incident status: **${r.status}**.`,
    `- Provider idempotency check: re-sent \`POST /transfers/create\` with the same request_id. Airwallex refused it (duplicate_request_id) and the adapter returned the existing transfer \`${replay.id}\` (providerDuplicate=${replay.providerDuplicate}).`,
    `- Transfers with that request_id: ${sameKey ? 1 : 0} (no second payment).`,
  ]);
}

// 2. Bad beneficiary
{
  const i = await c.simulate("bad-beneficiary");
  const r = await c.run(i.id);
  const plannedStatus = r.status;
  const approval = c.queue.items.find((a) => a.incidentId === i.id);
  const decided = approval ? await c.decide(approval.id, true, "Josh (sandbox run)", "Verify bank details by phone") : undefined;
  const b = await aw.getBeneficiary("vendor-bad");
  const retry = await c.execute({
    type: "retry",
    payoutId: i.payout!.id,
    beneficiaryId: "vendor-bad",
    amount: i.payout!.amount,
    currency: "USD",
    reference: i.payout!.reference,
    idempotencyKey: "retry-" + i.id,
  });
  const ok = i.payout!.status === "failed" && retry.startsWith("Blocked") && !!decided?.outcome?.startsWith("Manual");
  summary.push(`| 2. Bad beneficiary | ${ok ? "PASS" : "CHECK"} | Transfer FAILED (${i.payout!.failureCode}: ${i.payout!.failureReason}) -> sandbox settled it as CANCELLED; repair escalated to human, approval = manual task only; retry blocked because beneficiary is now invalid |`);
  section("2. Failed payout: invalid beneficiary", [
    `- Created transfer \`${i.payout!.id}\` ($${i.payout!.amount} USD) to vendor-bad, simulated SENT -> FAILED with failure_type INVALID_ACCOUNT_NAME_OR_NUMBER.`,
    `- Airwallex returned provider status **${i.payout!.providerStatus}** with failure \`${i.payout!.failureCode}\`: "${i.payout!.failureReason}" (adapter maps this to \`failed\`).`,
    `- Agent plan: ${r.actions!.map((a) => a.action.type + " => " + a.policy.decision + " (" + a.policy.ruleHits.join(", ") + ")").join("; ")}. Incident status after planning: **${plannedStatus}**; after approval: **${r.status}**.`,
    `- Human approval: ${decided?.status} -> "${decided?.outcome}".`,
    `- Live beneficiary check: vendor-bad valid=${b.valid} (stored details still pass Airwallex validation, but a transfer to it failed with a routing error).`,
    `- Direct retry attempt (bypassing the planner): "${retry}". No new transfer created.`,
  ]);
}

// 3. Stuck transfer
{
  const i = await c.simulate("stuck");
  const r = await c.run(i.id);
  const replacement = await c.execute({
    type: "create",
    beneficiaryId: "vendor-acme",
    amount: i.payout!.amount,
    currency: "USD",
    reference: i.payout!.reference,
    idempotencyKey: "replacement-" + i.id,
  });
  const live = await aw.getPayout(i.payout!.id);
  const ok = r.status === "manual_review" && replacement.startsWith("Blocked");
  summary.push(`| 3. Stuck transfer | ${ok ? "PASS" : "CHECK"} | Transfer left in ${live.providerStatus}; agent reconciled read-only -> manual review; replacement payment blocked (duplicate-invoice) |`);
  section("3. Stuck transfer", [
    `- Created transfer \`${i.payout!.id}\` ($${i.payout!.amount} USD) and left it in **${i.payout!.providerStatus}** (sandbox does not advance it without a simulation call).`,
    `- Agent plan: ${r.actions!.map((a) => a.action.type + " => " + a.policy.decision + ": " + a.outcome).join("; ")}. Incident status: **${r.status}**.`,
    `- Replacement payment attempt (new request_id, same invoice): "${replacement}".`,
    `- Re-read after the run: provider status ${live.providerStatus}.`,
    `- Note: the real transfer is minutes old, not 48 hours. The 24-hour SLA age is only reproducible in mock mode; in sandbox the "stuck" signal is the unresolved PROCESSING status.`,
  ]);
}

// 4. Over-limit purchase
{
  const before = (await aw.balances()).find((b) => b.currency === "USD");
  const i = await c.simulate("purchase");
  const r = await c.run(i.id);
  const key = r.actions![0].action.idempotencyKey;
  const created = await aw.findByRequestId(key);
  const after = (await aw.balances()).find((b) => b.currency === "USD");
  const ok = r.status === "blocked" && !created;
  summary.push(`| 4. Over-limit purchase | ${ok ? "PASS" : "CHECK"} | $1,800 off-intent purchase denied (${r.actions![0].policy.ruleHits.join(", ")}); Airwallex lookup by request_id found no transfer |`);
  section("4. Purchasing agent exceeded user intent", [
    `- Intent: office chair, office category, max $400. Agent requested: ${r.actions![0].action.item} (${r.actions![0].action.merchantCategory}) for $${r.actions![0].action.amount}.`,
    `- Policy: ${r.actions![0].policy.decision} (${r.actions![0].policy.ruleHits.join(", ")}). Incident status: **${r.status}**.`,
    `- No Airwallex call to create a transfer was made. Lookup \`GET /transfers?request_id=${key}\` returned ${created ? "a transfer (unexpected)" : "no transfer"}.`,
    `- USD available before/after this scenario: ${before?.available_amount} / ${after?.available_amount}.`,
  ]);
}

md.splice(4, 0, "", "## Summary", "", "| Scenario | Result | What Airwallex returned |", "| --- | --- | --- |", ...summary);
md.push("## Audit trail", "", `Hash-chained audit log verified: ${JSON.stringify(c.audit.verify())}.`, "");
const text = md.join("\n");
for (const secret of [process.env.AIRWALLEX_CLIENT_ID, process.env.AIRWALLEX_API_KEY])
  if (secret && text.includes(secret)) throw new Error("Refusing to write log: it contains a credential");
const out = resolve(import.meta.dirname, "../../docs/SANDBOX_RUN_LOG.md");
writeFileSync(out, text);
console.log("wrote", out);
console.log(summary.join("\n"));
